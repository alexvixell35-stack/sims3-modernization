// Generates native/ts3native/stallnames.h: the function name table [StallWatch] Names=1 resolves TS3W frames with (docs/666 §5).
//   node tools/native-names.ts [--functions <functions.csv>] [--out <file>]   write the header
//   node tools/native-names.ts --self-check
// Names: tools/ghidra/symbols/ts3w-1.67.symbols.csv (our own names, rows of type function / icall). Function ends:
// game-copy/analysis/functions.csv (tools/ghidra/ExportFunctions.java, local only: entry,end,name). A named entry with no
// function row gets no table row (no end = a frame past it could be misnamed). The header holds image offsets (address -
// 0x400000) and our names only, no exe bytes.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = process.env.TS3_REPO ?? join(import.meta.dirname, '..');
const BASE = 0x400000;
export type Row = { lo: number; len: number; name: string };

export function build(symbolsCsv: string, functionsCsv: string): Row[] {
  const end = new Map<number, number>();
  for (const l of functionsCsv.split(/\r?\n/).slice(1)) {
    const [e, x] = l.split(',');
    if (e && x) end.set(parseInt(e, 16), parseInt(x, 16));
  }
  const rows: Row[] = [];
  for (const l of symbolsCsv.split(/\r?\n/).slice(1)) {
    const m = l.match(/^0x([0-9A-Fa-f]+),([A-Za-z_][\w.:<>]*),(?:function|icall)\b/);
    if (!m) continue;
    const at = parseInt(m[1], 16), hi = end.get(at);
    if (hi === undefined || hi < at || at < BASE || hi - at > 0xFFFF) continue;
    rows.push({ lo: at - BASE, len: hi - at + 1, name: m[2].slice(0, 63) });
  }
  rows.sort((a, b) => a.lo - b.lo);
  return rows.filter((r, i) => i === 0 || r.lo >= rows[i - 1].lo + rows[i - 1].len);  // no overlap: the lookup is a binary search
}

export function header(rows: Row[]): string {
  const hex = (n: number, w: number) => '0x' + n.toString(16).toUpperCase().padStart(w, '0');
  return [
    '// Generated by tools/native-names.ts from tools/ghidra/symbols/ts3w-1.67.symbols.csv (our names) and a local Ghidra function',
    `// export (function ends). ${rows.length} rows sorted by offset: {image offset (Steam 1.67 address - 0x400000), length, name}. No exe bytes.`,
    '#pragma once',
    'struct SsSym { unsigned long lo, len; const char* name; };',
    'static const SsSym kSsSyms[] = {',
    ...rows.map(r => `    {${hex(r.lo, 6)}, ${hex(r.len, 4)}, "${r.name}"},`),
    '};',
    '',
  ].join('\n');
}

function selfCheck(): boolean {
  const sym = 'address,name,type,comment\n0x00401000,Alpha,function,x\n0x00401100,IC_Beta,icall,"a, b"\n0x00401200,gData,data,x\n0x00401300,NoEnd,function,x\n0x00401010,Inside,function,x\n';
  const fn = 'entry,end,name\n0x401000,0x40103e,FUN_00401000\n0x401010,0x401020,FUN_00401010\n0x401100,0x4011ff,FUN_00401100\n0x401200,0x401210,x\n';
  const r = build(sym, fn), h = header(r);
  const ok = r.length === 2 && r[0].lo === 0x1000 && r[0].len === 0x3F && r[1].name === 'IC_Beta' && r[1].len === 0x100
    && h.includes('{0x001000, 0x003F, "Alpha"},') && !h.includes('gData') && !h.includes('NoEnd') && !h.includes('Inside');
  console.log(ok ? 'native-names self-check ok' : `native-names self-check FAILED ${JSON.stringify(r)}`);
  return ok;
}

if (import.meta.filename === resolve(process.argv[1] ?? '')) {
  const argv = process.argv.slice(2);
  if (argv.includes('--self-check')) process.exit(selfCheck() ? 0 : 1);
  const val = (k: string, d: string) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
  const fnPath = val('--functions', join(ROOT, 'game-copy', 'analysis', 'functions.csv'));
  const out = val('--out', join(ROOT, 'native', 'ts3native', 'stallnames.h'));
  if (!existsSync(fnPath)) { console.error(`no ${fnPath}: run tools/ghidra/ExportFunctions.java first (local only)`); process.exit(2); }
  const rows = build(readFileSync(join(ROOT, 'tools', 'ghidra', 'symbols', 'ts3w-1.67.symbols.csv'), 'utf8'), readFileSync(fnPath, 'utf8'));
  writeFileSync(out, header(rows));
  console.log(`${out}: ${rows.length} rows`);
}
